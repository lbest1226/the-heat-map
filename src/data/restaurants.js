export function heatLevelToLabel(level) {
  if (level <= 3) return "MILD";
  if (level <= 5) return "MEDIUM";
  if (level <= 6) return "HOT";
  if (level <= 7) return "DAMN HOT";
  if (level <= 8) return "FIRE";
  return "SHUT THE CLUCK UP";
}

